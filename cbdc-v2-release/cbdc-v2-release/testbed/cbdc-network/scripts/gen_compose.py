"""Generate compose/docker-compose.yaml from scripts/nodes.py (run: python3 scripts/gen_compose.py).
Every Fabric container is limited to CPU cores 0-5 (SUT_CPUS), leaving cores 6-7 for the load generator
(Caliper), so client and system under test do not compete for the same cores."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from nodes import all_nodes, fill, IMG_TAG
SUT_CPUS = os.environ.get("SUT_CPUS", "0-5")
lines = ["# GENERATED by scripts/gen_compose.py from scripts/nodes.py; do not edit by hand.",
         "# Fabric " + IMG_TAG + " images pinned explicitly. All Fabric containers on CPU cores " + SUT_CPUS + ".",
         "name: cbdc", "", "networks:", "  cbdc_net:", "    name: cbdc_net", "", "volumes:"]
for n in all_nodes():
    lines.append(f"  {n['host']}:")
lines += ["", "services:"]
for n in all_nodes():
    if n["kind"] == "orderer":
        inner = {"MSP": "/var/hyperledger/orderer/msp", "TLS": "/var/hyperledger/orderer/tls", "DATA": n["data"], "CFG": ""}
        image, cmd = f"hyperledger/fabric-orderer:{IMG_TAG}", "orderer"
        vols = [f"../{n['msp']}:/var/hyperledger/orderer/msp", f"../{n['tls']}:/var/hyperledger/orderer/tls",
                f"{n['host']}:{n['data']}"]
    else:
        inner = {"MSP": "/etc/hyperledger/fabric/msp", "TLS": "/etc/hyperledger/fabric/tls", "DATA": n["data"],
                 "CFG": "/etc/hyperledger/peercfg"}
        image, cmd = f"hyperledger/fabric-peer:{IMG_TAG}", "peer node start"
        vols = [f"../{n['msp']}:/etc/hyperledger/fabric/msp", f"../{n['tls']}:/etc/hyperledger/fabric/tls",
                "../config/peercfg:/etc/hyperledger/peercfg", f"{n['host']}:{n['data']}"]
    lines += [f"  {n['host']}:", f"    container_name: {n['host']}", f"    image: {image}",
              f"    cpuset: \"{SUT_CPUS}\"", "    environment:"]
    for k, v in n["env"].items():
        lines.append(f"      - '{k}={fill(v, inner)}'")
    lines += ["    working_dir: /root", f"    command: {cmd}", "    volumes:"] + [f"      - {v}" for v in vols]
    lines += ["    ports:"] + [f"      - \"{p}:{p}\"" for p in n["ports"]]
    lines += ["    networks:", "      - cbdc_net", ""]
os.makedirs(os.path.join(os.path.dirname(__file__), "..", "compose"), exist_ok=True)
open(os.path.join(os.path.dirname(__file__), "..", "compose", "docker-compose.yaml"), "w").write("\n".join(lines))
print("wrote compose/docker-compose.yaml with", len(all_nodes()), "services")
